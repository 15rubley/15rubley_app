    @Synchronized
    fun generateComplaintCall(
        id: Long,
        orderTitle: String?,
        accumulatedBreakdowns: List<BikeBreakdownAlert> = emptyList(),
        currentGear: Int = 1
    ): IncomingComplaintCall {
        val availableScenarios = scenarios.filterNot { seenPlotIds.contains(it.plotId) }
            .ifEmpty { scenarios }
        val scenario = availableScenarios[Random.nextInt(availableScenarios.size)]
        seenPlotIds.addLast(scenario.plotId)
        if (seenPlotIds.size > scenarios.size - 2) {
            seenPlotIds.removeFirst()
        }

        val witness = witnesses[Random.nextInt(witnesses.size)]
        val evidence = absurdEvidence[Random.nextInt(absurdEvidence.size)]
        val contextOrder = orderTitle?.takeIf { it.isNotBlank() } ?: scenario.defaultOrder

        val openingCandidates = buildList {
            scenario.openings.forEach { raw ->
                add(fillPlaceholders(raw, witness, evidence, contextOrder, currentGear))
            }
            if (accumulatedBreakdowns.isNotEmpty()) {
                val issue = accumulatedBreakdowns[Random.nextInt(accumulatedBreakdowns.size)]
                add(
                    "Алло!! Это ${scenario.callerName}! Ваш велосипед грохочет из-за поломки «${issue.title}» — " +
                        "весь заказ «$contextOrder» под угрозой, даже $witness в шоке!"
                )
            }
            if (currentGear >= 4) {
                val callout = if (currentGear == 4) "V1" else "ROTATE"
                add(
                    "Алло! Вы почему мимо нас неслись на $currentGear-й передаче с криком «$callout»?! " +
                        "После этого с заказом «$contextOrder» творится какой-то кошмар!"
                )
            }
        }

        val opening = pickFresh(openingCandidates, recentOpenings, maxCache = 18)
        val initialAnger = Random.nextInt(20, 32)
        val maxTurns = Random.nextInt(3, 6) // 3 to 5 turns before guaranteed snap unless anger hits 100 earlier

        val turn1Choices = pickTurnOptions(
            scenario = scenario,
            turnNumber = 1,
            usedOptionIds = emptySet(),
            usedOptionLabels = emptySet(),
            allowTip = true,
            witness = witness,
            evidence = evidence,
            orderContext = contextOrder,
            currentGear = currentGear
        )

        return IncomingComplaintCall(
            id = id,
            plotId = scenario.plotId,
            callerName = scenario.callerName,
            callerRole = scenario.callerRole,
            phoneLabel = scenario.phone,
            orderContext = contextOrder,
            avatarColorHex = scenario.avatarHex,
            openingComplaint = opening,
            currentClientLine = opening,
            dialogueHistory = listOf(
                CallDialogueLine(
                    id = 1L,
                    speakerName = scenario.callerName,
                    text = opening,
                    isFromCourier = false
                )
            ),
            turnNumber = 1,
            maxTurns = maxTurns,
            clientAngerPercent = initialAnger,
            isClientReacting = false,
            droppedByClient = false,
            accumulatedRatingDelta = 0.0,
            accumulatedTipRub = 0,
            usedOptionIds = turn1Choices.map { it.id }.toSet(),
            usedOptionLabels = turn1Choices.map { it.label }.toSet(),
            activeTwistLabel = evidence,
            activeWitnessLabel = witness,
            status = CallStatus.RINGING,
            responseOptions = turn1Choices
        )
    }

    @Synchronized
    fun advanceCallTurn(
        call: IncomingComplaintCall,
        chosenOption: CallResponseOption,
        accumulatedBreakdowns: List<BikeBreakdownAlert> = emptyList(),
        currentGear: Int = 1
    ): CallTurnResolution {
        val scenario = scenarios.firstOrNull { it.plotId == call.plotId } ?: scenarios.first()
        val courierText = chosenOption.spokenReply.ifBlank { chosenOption.label }
        val nextHistoryIdBase = (call.dialogueHistory.maxOfOrNull { it.id } ?: 0L) + 1L

        val historyWithCourier = call.dialogueHistory + CallDialogueLine(
            id = nextHistoryIdBase,
            speakerName = "Вы",
            text = courierText,
            isFromCourier = true,
            angerDelta = chosenOption.angerDelta
        )

        val rawNextAnger = call.clientAngerPercent + chosenOption.angerDelta
        // Never allow client to hang up immediately after the very 1st reply — always extend at least to turn 2!
        val effectiveAnger = if (call.turnNumber == 1) {
            rawNextAnger.coerceIn(38, 82)
        } else {
            rawNextAnger.coerceIn(call.clientAngerPercent + 12, 100)
        }

        val shouldSnap = (call.turnNumber >= 2 && effectiveAnger >= 100) || call.turnNumber >= call.maxTurns
        val updatedUsedIds = call.usedOptionIds + chosenOption.id
        val nextAccumulatedRating = call.accumulatedRatingDelta + chosenOption.ratingDelta
        val nextAccumulatedTip = call.accumulatedTipRub + chosenOption.tipRub
        val existingTexts = historyWithCourier.map { it.text }.toSet()

        if (shouldSnap) {
            val reactionPrefix = buildStyleReactionPrefix(
                styleTag = chosenOption.styleTag,
                witness = call.activeWitnessLabel,
                evidence = call.activeTwistLabel,
                isSnapping = true
            )
            val explosionRaw = pickFresh(
                scenario.explosions.map {
                    fillPlaceholders(it, call.activeWitnessLabel, call.activeTwistLabel, call.orderContext, currentGear)
                },
                recentFollowUps,
                maxCache = 20,
                avoid = existingTexts
            )
            val finalExplosion = "$reactionPrefix $explosionRaw".trim()
            val finalHistory = historyWithCourier + CallDialogueLine(
                id = nextHistoryIdBase + 1L,
                speakerName = call.callerName,
                text = finalExplosion,
                isFromCourier = false
            )

            val snapPenalty = if (nextAccumulatedRating > -0.25) -0.1 else 0.0
            val totalRating = nextAccumulatedRating + snapPenalty
            val deltaText = "${if (totalRating >= 0) "+" else ""}${String.format(Locale.US, "%.1f", totalRating)}★"
            val tipSuffix = if (nextAccumulatedTip > 0) " • +${nextAccumulatedTip}₽" else ""

            val endedCall = call.copy(
                currentClientLine = finalExplosion,
                courierLine = courierText,
                dialogueHistory = finalHistory,
                turnNumber = call.turnNumber,
                clientAngerPercent = 100,
                isClientReacting = false,
                droppedByClient = true,
                accumulatedRatingDelta = totalRating,
                accumulatedTipRub = nextAccumulatedTip,
                usedOptionIds = updatedUsedIds,
                status = CallStatus.ENDED,
                resolutionNote = "Клиент сорвался на ${call.turnNumber}-м ответе • $deltaText$tipSuffix",
                responseOptions = emptyList()
            )
            return CallTurnResolution(
                updatedCall = endedCall,
                didClientSnap = true,
                clientSpokenLine = finalExplosion,
                snapRatingPenalty = snapPenalty
            )
        }

        // Client keeps arguing and escalates!
        val nextTurn = call.turnNumber + 1
        val hookPoolRaw = when (nextTurn) {
            2 -> scenario.stage2Hooks
            3 -> scenario.stage3Hooks
            else -> scenario.stage4Hooks + scenario.stage3Hooks
        }
        val extraBreakdownHook = accumulatedBreakdowns.firstOrNull()?.let { issue ->
            listOf("И не делайте вид, что не знаете про «${issue.title}» — я это даже по телефону слышу!")
        }.orEmpty()

        val hydratedHooks = (hookPoolRaw + extraBreakdownHook).map {
            fillPlaceholders(it, call.activeWitnessLabel, call.activeTwistLabel, call.orderContext, currentGear)
        }
        val nextHook = pickFresh(hydratedHooks, recentFollowUps, maxCache = 24, avoid = existingTexts)
        val reactionPrefix = buildStyleReactionPrefix(
            styleTag = chosenOption.styleTag,
            witness = call.activeWitnessLabel,
            evidence = call.activeTwistLabel,
            isSnapping = false
        )
        val nextClientLine = "$reactionPrefix $nextHook".trim()

        val nextOptions = pickTurnOptions(
            scenario = scenario,
            turnNumber = nextTurn,
            usedOptionIds = updatedUsedIds,
            usedOptionLabels = call.usedOptionLabels + chosenOption.label,
            allowTip = nextAccumulatedTip == 0,
            witness = call.activeWitnessLabel,
            evidence = call.activeTwistLabel,
            orderContext = call.orderContext,
            currentGear = currentGear
        )

        val updatedHistory = historyWithCourier + CallDialogueLine(
            id = nextHistoryIdBase + 1L,
            speakerName = call.callerName,
            text = nextClientLine,
            isFromCourier = false
        )

        val activeCall = call.copy(
            currentClientLine = nextClientLine,
            courierLine = courierText,
            dialogueHistory = updatedHistory,
            turnNumber = nextTurn,
            clientAngerPercent = effectiveAnger,
            isClientReacting = false,
            droppedByClient = false,
            accumulatedRatingDelta = nextAccumulatedRating,
            accumulatedTipRub = nextAccumulatedTip,
            usedOptionIds = updatedUsedIds + nextOptions.map { it.id },
            usedOptionLabels = call.usedOptionLabels + chosenOption.label + nextOptions.map { it.label },
            status = CallStatus.ACTIVE,
            responseOptions = nextOptions
        )
        return CallTurnResolution(
            updatedCall = activeCall,
            didClientSnap = false,
            clientSpokenLine = nextClientLine
        )
    }

