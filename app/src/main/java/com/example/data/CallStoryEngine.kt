    private fun pickTurnOptions(
        scenario: CallScenario,
        turnNumber: Int,
        usedOptionIds: Set<String>,
        usedOptionLabels: Set<String>,
        allowTip: Boolean,
        witness: String,
        evidence: String,
        orderContext: String,
        currentGear: Int
    ): List<CallResponseOption> {
        val primaryPool = when (turnNumber) {
            1 -> scenario.turn1Options
            2 -> scenario.turn2Options
            3 -> scenario.turn3Options
            else -> scenario.lateOptions
        }
        val backupPool = (scenario.turn1Options + scenario.turn2Options + scenario.turn3Options + scenario.lateOptions)

        val dynamicBonusPool = listOf(
            ScenarioOptionSeed("dyn_t${turnNumber}_wind", "Отмазка", "Во всём виноват встречный ветер и кочки у бордюра!", 26, -0.1),
            ScenarioOptionSeed("dyn_t${turnNumber}_gear", "Тех-аргумент", "На ${currentGear}-й передаче по-другому физически не выйдет!", 32, -0.2),
            ScenarioOptionSeed("dyn_t${turnNumber}_calm", "Вежливо", "Простите, у меня смена уже 5 часов без отдыха...", 20, 0.0),
            ScenarioOptionSeed("dyn_t${turnNumber}_15", "Взятка 15₽", "Давайте закроем вопрос за 15₽ на лечение нервов?", 30, -0.1, tipRub = 15),
            ScenarioOptionSeed("dyn_t${turnNumber}_boeing", "Боинг V1", "Не могу снизить обороты — шасси выпущены, иду на V1!", 42, -0.3),
            ScenarioOptionSeed("dyn_t${turnNumber}_witness", "Стрелки", "Во всём виноват {witness}, я вообще мимо проезжал!", 34, -0.2),
            ScenarioOptionSeed("dyn_t${turnNumber}_garage", "Тех-аргумент", "Прямо сейчас сворачиваю в велогараж на капремонт!", 22, -0.1),
            ScenarioOptionSeed("dyn_t${turnNumber}_order", "Отмазка", "С заказом «{order}» всегда так бывает по пятницам!", 28, -0.2)
        )

        val isFresh = { seed: ScenarioOptionSeed ->
            val fullId = "${scenario.plotId}_${seed.key}"
            val hydrated = fillPlaceholders(seed.label, witness, evidence, orderContext, currentGear)
            fullId !in usedOptionIds && hydrated !in usedOptionLabels && (allowTip || seed.tipRub == 0)
        }

        val chosen = mutableListOf<ScenarioOptionSeed>()
        val usedStyles = mutableSetOf<String>()

        for (seed in primaryPool.shuffled()) {
            if (!isFresh(seed)) continue
            if (seed.styleTag !in usedStyles) {
                chosen += seed
                usedStyles += seed.styleTag
                if (chosen.size == 3) break
            }
        }
        if (chosen.size < 3) {
            val candidates = (primaryPool + backupPool + dynamicBonusPool)
                .distinctBy { it.key }
                .filter(isFresh)
                .shuffled()
            for (seed in candidates) {
                if (chosen.any { it.key == seed.key }) continue
                if (seed.styleTag !in usedStyles || chosen.size >= 2) {
                    chosen += seed
                    usedStyles += seed.styleTag
                    if (chosen.size == 3) break
                }
            }
        }

        return chosen.take(3).map { seed ->
            val hydrated = fillPlaceholders(seed.label, witness, evidence, orderContext, currentGear)
            CallResponseOption(
                id = "${scenario.plotId}_${seed.key}",
                label = hydrated,
                spokenReply = hydrated,
                styleTag = seed.styleTag,
                angerDelta = seed.angerDelta,
                ratingDelta = seed.ratingDelta,
                tipRub = seed.tipRub
            )
        }
    }

