    private fun fillPlaceholders(
        template: String,
        witness: String,
        evidence: String,
        orderContext: String,
        currentGear: Int
    ): String {
        return template
            .replace("{witness}", witness)
            .replace("{evidence}", evidence)
            .replace("{order}", orderContext)
            .replace("{gear}", currentGear.toString())
    }

    private fun pickFresh(
        pool: List<String>,
        recentCache: ArrayDeque<String>,
        maxCache: Int,
        avoid: Set<String> = emptySet()
    ): String {
        val fresh = pool.filterNot { recentCache.contains(it) || avoid.contains(it) }
        val nonAvoid = if (fresh.isNotEmpty()) fresh else pool.filterNot { avoid.contains(it) }
        val source = if (nonAvoid.isNotEmpty()) nonAvoid else pool
        val picked = source[Random.nextInt(source.size)]
        recentCache.addLast(picked)
        while (recentCache.size > maxCache) {
            recentCache.removeFirst()
        }
        return picked
    }
